    public HistorialForm(Inicio inicio, DefaultListModel<Cancion> historial) {
        this.inicio = inicio;
        this.historial = historial;
        initComponents();
        
        listadoHistorial.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent evt) {
                if (evt.getClickCount() == 2) {
                    Cancion seleccionada = listadoHistorial.getSelectedValue();
                    
                        if (seleccionada == null) {
                            JOptionPane.showMessageDialog(null, "Debe seleccionar una cancion si quiere reproducir", "ADVERTENCIA", JOptionPane.WARNING_MESSAGE);
                            return;
                        }
                        
                        inicio.reproductor.setModo(inicio.modoReproduccionCombo.getSelectedIndex() + 1);
                        inicio.reproductor.reproducir(seleccionada, inicio.playlists.getFirst());
                        inicio.playlistEnReproduccionLbl.setText(seleccionada.nombre);
                        dispose();
                    
                }
            }
            
        });
    }

